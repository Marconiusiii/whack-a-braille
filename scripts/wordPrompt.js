function buildWordPrompt(word, spellAll = false) {
	const text = String(word || "");
	if (!text || (!spellAll && !homophoneTargets.has(text.toLowerCase()))) {
		return text;
	}
	return text + ", " + Array.from(text).join(" ");
}

function isHomophoneTarget(word) {
	return homophoneTargets.has(String(word || "").toLowerCase());
}

